"""Facade pin fixture: every pinned name resolves on ``eve`` and the fixture is current.

Program task 0.3 (docs/architecture/EVE_REARCHITECTURE_PROGRAM_2026_09_17.md).
``tests/fixtures/eve_facade_pins.txt`` is generated by ``bin/eve_facade_pins.py``
from the test-suite's patches and ``eve.<name>`` references, the CLI parser's
``HANDLER_NAMES``/``SETTING_NAMES``, and ``eve.py``'s ``globals().get`` lookups.
Any extraction that drops a name from the facade fails here first.
"""
import importlib.util
import os
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "tests" / "fixtures" / "eve_facade_pins.txt"
GENERATOR = ROOT / "bin" / "eve_facade_pins.py"

_spec = importlib.util.spec_from_file_location("eve_facade_pins", str(GENERATOR))
pins = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pins)


class FacadePinFixtureTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.fixture_names = pins.read_fixture(str(ROOT))
        cls.sources = pins.collect_sources(str(ROOT))
        cls.regenerated = pins.pinned_names(str(ROOT), cls.sources)

    def test_fixture_exists_and_is_well_formed(self):
        self.assertTrue(FIXTURE.exists(), "missing %s; run bin/eve_facade_pins.py" % FIXTURE)
        names = self.fixture_names
        self.assertGreater(len(names), 1000, "fixture suspiciously small: %d names" % len(names))
        self.assertEqual(names, sorted(names), "fixture is not sorted")
        self.assertEqual(len(names), len(set(names)), "fixture has duplicate lines")
        for name in names:
            self.assertTrue(name.isidentifier(), "not an identifier: %r" % name)

    def test_every_source_contributes(self):
        for key in pins.SOURCE_KEYS:
            self.assertTrue(self.sources[key], "source %r produced no names" % key)
        # Spot checks that the four sources really were read.
        self.assertIn("cmd_daemon_run", self.sources["handler_names"])
        self.assertIn("DEFAULT_CONFIG", self.sources["setting_names"])
        self.assertIn("cmd_governance_apply", self.sources["globals_lookups"])
        self.assertIn("utc_now", self.sources["attribute_references"])

    def test_fixture_is_up_to_date(self):
        if self.fixture_names != self.regenerated:
            diff = pins.fixture_diff(self.fixture_names, self.regenerated)
            self.fail(
                "tests/fixtures/eve_facade_pins.txt is stale (%d on disk, %d regenerated); "
                "run: python3 bin/eve_facade_pins.py\n%s" % (len(self.fixture_names), len(self.regenerated), diff)
            )

    def test_every_pinned_name_resolves_on_the_facade(self):
        import eve

        missing = [name for name in self.fixture_names if not hasattr(eve, name)]
        self.assertEqual(
            missing,
            [],
            "%d pinned name(s) no longer resolve on eve (the facade contract is broken): %s"
            % (len(missing), ", ".join(missing[:40])),
        )

    def test_handlers_and_settings_are_facade_bound(self):
        # eve.py injects globals()[name] for these eagerly (eve.py, near
        # cmd registration); the parser cannot start if any is absent.
        import eve

        for name in sorted(self.sources["handler_names"]):
            self.assertTrue(callable(getattr(eve, name, None)), "handler %s is not callable on eve" % name)
        for name in sorted(self.sources["setting_names"]):
            self.assertTrue(hasattr(eve, name), "setting %s missing on eve" % name)


class FacadePinGeneratorTests(unittest.TestCase):
    """The generator's readers on small synthetic inputs (no repo dependence)."""

    def test_patch_forms_are_collected(self):
        import ast

        source = (
            "from unittest import mock\n"
            "from unittest.mock import patch\n"
            "def t():\n"
            "    with patch.object(eve, 'alpha'): pass\n"
            "    with mock.patch.object(eve, \"beta\", return_value=1): pass\n"
            "    with patch('eve.gamma'): pass\n"
            "    with mock.patch('eve.delta.inner'): pass\n"
            "    with patch.dict('eve.epsilon', {}): pass\n"
            "    with patch.multiple(eve, zeta=1, eta=2): pass\n"
            "    with patch.object(other, 'ignored'): pass\n"
            "    with patch('other.ignored'): pass\n"
            "    x = eve.theta\n"
            "    y = 'eve.py'\n"
        )
        tree = ast.parse(source)
        self.assertEqual(
            pins.collect_patch_targets(tree),
            {"alpha", "beta", "gamma", "delta", "epsilon", "zeta", "eta"},
        )
        self.assertEqual(pins.collect_attribute_references(tree), {"theta"})

    def test_globals_lookups_are_collected(self):
        import ast

        tree = ast.parse(
            "a = callable(globals().get('cmd_one'))\n"
            "b = globals().get(\"cmd_two\", None)\n"
            "c = other.get('nope')\n"
            "d = globals()['cmd_three']\n"
        )
        self.assertEqual(pins.collect_globals_lookups(tree), {"cmd_one", "cmd_two"})

    def test_render_and_parse_round_trip(self):
        text = pins.render(["b", "a", "b"])
        self.assertEqual(text, "a\nb\n")
        self.assertEqual(pins.parse_fixture("# comment\n\na\nb\n"), ["a", "b"])


if __name__ == "__main__":
    unittest.main()
