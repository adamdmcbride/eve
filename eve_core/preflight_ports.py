"""Effect ownership for one pre-answer conversation workflow."""
from typing import Dict, List, Optional, Protocol


class ConversationEvidence(Protocol):
    def resolve_operator(self) -> Optional[Dict[str, object]]: ...
    def needs_thread(self, body: str) -> bool: ...
    def read_thread(self) -> List[Dict[str, object]]: ...


class ConversationPerception(Protocol):
    def perceive(self, body: str, *, allow_semantic: bool,
                 thread_messages: Optional[List[Dict[str, object]]]) -> Dict[str, object]: ...
    def sparse(self, body: str) -> Dict[str, object]: ...


class ConversationContinuity(Protocol):
    def observe_previous(self) -> Optional[Dict[str, object]]: ...
    def refresh_social(self) -> Optional[Dict[str, object]]: ...
    def open_cycle(self, body: str, *, source: str, persist: bool,
                   frame: Dict[str, object], social: Optional[Dict[str, object]]) -> Dict[str, object]: ...
    def record_correction(self, body: str, *, target_message_id: str,
                          consequence_observed: bool, consequence_joined: bool) -> Optional[Dict[str, object]]: ...


class ConversationPreflightJournal(Protocol):
    def warning(self, kind: str, summary: str, metadata: Dict[str, object]) -> None: ...
