"""Narrow dependencies of the self-change use case, wired by the adapter."""
from dataclasses import dataclass, field
from typing import Dict, List, Mapping, Optional, Protocol, Tuple


@dataclass
class CodingSession:
    session_id: str
    backup_dir: str
    config: Dict[str, object]
    context: Dict[str, object] = field(default_factory=dict)


@dataclass(frozen=True)
class Verification:
    ok: bool
    detail: str


class Clock(Protocol):
    def utc(self) -> str: ...
    def monotonic(self) -> float: ...


class Proposals(Protocol):
    def archive_stale(self, config: Mapping[str, object]) -> None: ...
    def candidates(self, config: Mapping[str, object]) -> List[Dict[str, object]]: ...
    def update(self, proposal_id: str, status: str, metadata: Dict[str, object]) -> None: ...


class Coder(Protocol):
    authority_tools: Tuple[str, ...]
    def prepare(self, config: Mapping[str, object], now: str, proposal: Mapping[str, object], timeout: int) -> CodingSession: ...
    def execute(self, session: CodingSession, proposal: Mapping[str, object]) -> object: ...
    def verify(self, session: CodingSession, tests_ok: Optional[bool]) -> Verification: ...
    def rollback(self, session: CodingSession) -> List[str]: ...


class Runtime(Protocol):
    def synchronize(self) -> Mapping[str, object]: ...
    def restart(self, session: CodingSession, reason: str, code_changed: bool) -> bool: ...


class Journal(Protocol):
    def history(self) -> List[Dict[str, object]]: ...
    def entry(self, kind: str, text: str, metadata: Dict[str, object]) -> None: ...
    def write(self, row: Dict[str, object]) -> None: ...
    def follow_up(self, row: Dict[str, object], config: Mapping[str, object]) -> None: ...
    def notify(self, row: Dict[str, object]) -> None: ...
