"""Three dependencies of the nonacting reply-finalization use case."""
from typing import Mapping, Protocol, Tuple

from .replies import ReplyAssessment


class ReplyBoundary(Protocol):
    def prepare(self, text: str) -> str: ...
    def trim(self, text: str) -> str: ...
    def assess(self, text: str) -> ReplyAssessment: ...
    def ground(self, text: str, source: str) -> str: ...
    def fallback(self) -> str: ...


class ReplyAuthor(Protocol):
    model: str
    def rewrite(self, text: str, issues: Tuple[str, ...]) -> str: ...


class ReplyCritic(Protocol):
    def review(self, text: str) -> object: ...
    def correct(self, text: str, verdict: Mapping[str, object], max_tokens: int) -> object: ...
